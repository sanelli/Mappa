using Mappa.Generator.Extensions;
using Mappa.Generator.Models;
using Mappa.Generator.Models.Strategies;

using Microsoft.CodeAnalysis;

namespace Mappa.Generator.Helpers;

/// <summary>
/// Decorates a strategy with the value transformers that match the source and target types
/// of the mapping site being identified.
/// </summary>
internal static class ValueTransformerStrategyWrapper
{
    /// <summary>
    /// Wraps <paramref name="strategy"/> in a <see cref="ValueTransformerMapStrategy"/> when at least one
    /// transformer applies to the source and/or target type of the current mapping site.
    /// </summary>
    /// <param name="context">The context of the mapping site.</param>
    /// <param name="strategy">The strategy identified for the site.</param>
    /// <param name="compilation">The compilation.</param>
    /// <returns>
    /// The original strategy when there is nothing to apply (or when the strategy is a <see cref="NoMapStrategy"/>
    /// or the root map is a queryable projection); otherwise the decorated strategy.
    /// </returns>
    internal static MapStrategy Wrap(
        MappaMapAlgorithmContext context,
        MapStrategy strategy,
        Compilation compilation)
    {
        if (strategy is NoMapStrategy
            || context.ValueTransformerCatalog is not { IsEmpty: false } catalog
            || IsQueryableProjectionRoot(context, compilation))
        {
            return strategy;
        }

        var calleeMethod = GetSelfGeneratedCallee(strategy);
        var nullableEnabled = context.IsNullableEnabled();

        // A strategy whose types differ from the site types (for example the element strategy returned for
        // 'int' to 'int?') only participates on the sides that still match the site.
        var sourceTransformers = SelectForSide(
            catalog,
            context,
            strategy.SourceType,
            context.SourceType,
            calleeMethod?.SourceType,
            compilation);
        var targetTransformers = SelectForSide(
            catalog,
            context,
            strategy.TargetType,
            context.TargetType,
            calleeMethod?.TargetType,
            compilation);

        RemoveAlreadyApplied(strategy, sourceTransformers, targetTransformers, nullableEnabled);

        return sourceTransformers.Count == 0 && targetTransformers.Count == 0
            ? strategy
            : new ValueTransformerMapStrategy(strategy, [.. sourceTransformers], [.. targetTransformers]);
    }

    private static bool IsQueryableProjectionRoot(MappaMapAlgorithmContext context, Compilation compilation)
        => context.GetRootMapMethod().MethodSymbol?.IsQueryableProjectionMapMethod(compilation) == true;

    private static List<ValueTransformer> SelectForSide(
        ValueTransformerCatalog catalog,
        MappaMapAlgorithmContext context,
        ITypeSymbol strategyType,
        ITypeSymbol siteType,
        ITypeSymbol? selfGeneratedCalleeType,
        Compilation compilation)
        => HasSameType(strategyType, siteType)
            ? Select(catalog, context, siteType, selfGeneratedCalleeType, context.IsNullableEnabled(), compilation)
            : [];

    private static bool HasSameType(ITypeSymbol left, ITypeSymbol right)
        => SymbolEqualityComparer.IncludeNullability.Equals(left, right);

    /// <summary>
    /// Gets the invoked map method when it is generated by Mappa: its own root already applies
    /// the <c>[MappaTransformer]</c> transformers.
    /// </summary>
    private static MapMethod? GetSelfGeneratedCallee(MapStrategy strategy)
        => strategy is MethodMapStrategy { MapMethod: { } mapMethod }
           && (mapMethod.IsSynthetic || mapMethod.MethodDeclarationSyntax?.IsPartial() == true)
            ? mapMethod
            : null;

    private static List<ValueTransformer> Select(
        ValueTransformerCatalog catalog,
        MappaMapAlgorithmContext context,
        ITypeSymbol siteType,
        ITypeSymbol? selfGeneratedCalleeType,
        bool nullableEnabled,
        Compilation compilation)
    {
        var selected = new List<ValueTransformer>();
        var sourceMemberPath = context.SourceMemberPath;

        foreach (var applyTransformer in catalog.ApplyTransformers)
        {
            if ((applyTransformer.SourcePropertyName is null
                 || (sourceMemberPath is not null
                     && applyTransformer.SourcePropertyName.Equals(sourceMemberPath, StringComparison.Ordinal)))
                && ValueTransformerSignature.IsMatch(applyTransformer, siteType, nullableEnabled, compilation))
            {
                selected.Add(applyTransformer);
            }
        }

        var calleeAppliesClassTransformers = selfGeneratedCalleeType is not null
                                             && siteType.IsEqualTo(selfGeneratedCalleeType, nullableEnabled);
        if (calleeAppliesClassTransformers)
        {
            return selected;
        }

        // The predicate is evaluated lazily, so duplicates are detected against the items added so far.
        foreach (var classTransformer in catalog.ClassTransformers.Where(classTransformer =>
                     !selected.Exists(existing => existing.IsSameAs(classTransformer))
                     && ValueTransformerSignature.IsMatch(classTransformer, siteType, nullableEnabled, compilation)))
        {
            selected.Add(classTransformer);
        }

        return selected;
    }

    /// <summary>
    /// Removes the transformers that the wrapped strategy already applies to the very same value type,
    /// for example when a nullable wrapper delegates to an element strategy for the same non-null type.
    /// </summary>
    private static void RemoveAlreadyApplied(
        MapStrategy strategy,
        List<ValueTransformer> sourceTransformers,
        List<ValueTransformer> targetTransformers,
        bool nullableEnabled)
    {
        var appliedOnSource = new List<(ValueTransformer Transformer, ITypeSymbol Type)>();
        var appliedOnTarget = new List<(ValueTransformer Transformer, ITypeSymbol Type)>();
        CollectApplied(strategy, appliedOnSource, appliedOnTarget);

        sourceTransformers.RemoveAll(transformer => IsApplied(appliedOnSource, transformer, strategy.SourceType, nullableEnabled));
        targetTransformers.RemoveAll(transformer => IsApplied(appliedOnTarget, transformer, strategy.TargetType, nullableEnabled));
    }

    private static bool IsApplied(
        List<(ValueTransformer Transformer, ITypeSymbol Type)> applied,
        ValueTransformer transformer,
        ITypeSymbol type,
        bool nullableEnabled)
        => applied.Exists(entry => entry.Transformer.IsSameAs(transformer) && entry.Type.IsEqualTo(type, nullableEnabled));

    private static void CollectApplied(
        MapStrategy strategy,
        List<(ValueTransformer Transformer, ITypeSymbol Type)> appliedOnSource,
        List<(ValueTransformer Transformer, ITypeSymbol Type)> appliedOnTarget)
    {
        switch (strategy)
        {
            case ValueTransformerMapStrategy valueTransformerStrategy:
                appliedOnSource.AddRange(valueTransformerStrategy.SourceTransformers
                    .Select(transformer => (transformer, valueTransformerStrategy.SourceType)));
                appliedOnTarget.AddRange(valueTransformerStrategy.TargetTransformers
                    .Select(transformer => (transformer, valueTransformerStrategy.TargetType)));
                CollectApplied(valueTransformerStrategy.InnerStrategy, appliedOnSource, appliedOnTarget);
                break;
            case NullableStrategy nullableStrategy:
                CollectApplied(nullableStrategy.ElementStrategy, appliedOnSource, appliedOnTarget);
                break;
        }
    }
}