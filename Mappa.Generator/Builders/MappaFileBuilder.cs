using Mappa.Generator.Models;

namespace Mappa.Generator.Builders;

/// <summary>
/// Build a map for a file.
/// </summary>
internal sealed class MappaFileBuilder
    : IMappaBuilder
{
    /// <summary>
    /// Initializes a new instance of the <see cref="MappaFileBuilder"/> class.
    /// </summary>
    /// <param name="classContext">The class generator context.</param>
    public MappaFileBuilder(MappaClassGeneratorContext classContext)
    {
        this.ClassContext = classContext;
        this.HintName = $"{this.ClassContext.ClassSymbol.ToDisplayString()}.g.cs";
    }

    /// <summary>
    /// Gets the hint name.
    /// </summary>
    internal string HintName { get; }

    /// <summary>
    /// Gets the class generator context.
    /// </summary>
    private MappaClassGeneratorContext ClassContext { get; }

    /// <inheritdoc/>
    public string BuildSource(MappaBuilderContext context, MappaGlobalOptions mappaGlobalOptions)
    {
        // Build the source for the class (also registers any inaccessible accessors).
        var classSourceCode = new MappaClassBuilder(this.ClassContext).BuildSource(context, mappaGlobalOptions);

        // Emit file-local accessors inside the same namespace as the mapper (after a
        // file-scoped namespace declaration, or inside a block-scoped namespace).
        var inaccessibleAccessorsSource = context.InaccessibleAccessors.BuildSource();
        var preamble = string.IsNullOrWhiteSpace(inaccessibleAccessorsSource)
            ? null
            : inaccessibleAccessorsSource;

        var classSourceCodeWithNamespace = new MappaNamespaceBuilder(
                this.ClassContext,
                classSourceCode,
                preamble)
            .BuildSource(context, mappaGlobalOptions);

        var builder = new PrettyCode.StringBuilder();

        // Add the file command description and the class code with namespace.
        builder
            .AppendLine("// <auto-generated>")
            .AppendLine("//    <tool-name>Mappa</tool-name>")
            .AppendLine($"//    <tool-version>{MappaGeneratorConsts.MappaGeneratorVersion}</tool-version>")
            .AppendLine($"//    <timestamp>{DateTime.UtcNow:R}</timestamp>")
            .AppendLine("//    <note>This is an autogenerated file: edit to this file might be lost.</note>")
            .AppendLine("// </auto-generated>");
        builder.AppendEmptyLine();
        builder.AppendLine(classSourceCodeWithNamespace);

        return builder.ToString();
    }
}